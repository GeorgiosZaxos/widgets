# ---- symbols: names derived from Unicode, legacy labels kept as aliases ---------------
def symbols(group: str, mapping: dict[str, str]) -> list[tuple[str, str, str]]:
    seen: dict[str, tuple[str, str, str]] = {}
    for label, ch in mapping.items():
        if len(ch) != 1:
            continue
        uname = unicodedata.name(ch, label)
        key = uname.lower().replace(" ", "-")
        entry = seen.setdefault(key, (key, ch, group))
        _ = entry
    return list(seen.values())


