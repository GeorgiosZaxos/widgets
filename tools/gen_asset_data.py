HEAD = '"""GENERATED by tools/gen_asset_data.py from the legacy asset modules. Do not edit."""\n\nfrom __future__ import annotations\n\n'


def write(path: Path, body: str) -> None:
    path.write_text(HEAD + body, encoding="utf-8")


def fmt(name: str, value: object) -> str:
    return f"{name} = " + pprint.pformat(value, width=96, sort_dicts=True) + "\n\n"


def w(s: str) -> int:
    return sum(
        2 if unicodedata.east_asian_width(c) in "WF" else 0 if unicodedata.combining(c) else 1
        for c in s
    )


