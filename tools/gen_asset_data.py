for name, frames in S.SPINNER_STYLES.items():
    frames = list(frames)
    key = tuple(frames)
    if len(frames) < 2 or len({w(f) for f in frames}) != 1 or key in seen_frames:
        dropped.append(name)
        continue
    seen_frames.add(key)
    sp[name.replace("_", "-")] = frames
write(out / "assets" / "_spinner_data.py", fmt("SPINNERS", sp) + fmt("DROPPED", dropped))

